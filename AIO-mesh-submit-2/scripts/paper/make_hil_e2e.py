#!/usr/bin/env python3
"""Generate the end-to-end HIL tables (Section 6.7) from retained testbed records.

Inputs (relative to the package root) are the per-campaign analyses written by
scripts/hil/analyze_campaign.py, analyze_mbb.py and analyze_longrun.py, the live
fault-injection summary and the isolated BMv2 over-MSD summary. Nothing is typed in by hand.

Outputs: docs/AIO-mesh-rev1/generated/{table_hil_e2e.tex,
table_hil_e2e_detailed.tex, table_hil_msd.tex, table_hil_msd_detailed.tex,
table_hil_longrun.tex, hil_e2e_numbers.tex, hil_e2e.json}.
Usage: python3 scripts/paper/make_hil_e2e.py
"""
from __future__ import annotations

import csv
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUN = ROOT / "results/rev1/hil_e2e_20261121/run"
OVERMSD = ROOT / "results/hil_export/hil_rev1_20261121/generated/overmsd/overmsd_summary.json"
GEN = ROOT / "docs/AIO-mesh-rev1/generated"
CAMPAIGNS = [("corrected", "campaign_corrected_model", "analysis_mbb_corrected_model"),
             ("legacy", "campaign", "analysis_mbb")]
LONGRUNS = [("released", "long_3h_corrected_model_released")]
used: dict[str, str] = {}


def load(p: Path):
    used[str(p.relative_to(ROOT))] = hashlib.sha256(p.read_bytes()).hexdigest()
    return json.loads(p.read_text()) if p.suffix == ".json" else list(csv.DictReader(p.open()))


def n(x) -> str:
    return f"{x:,}"


def f(x, d=2) -> str:
    return f"{float(x):.{d}f}"


def pcts(row, d=2) -> str:
    return f"{f(row['p50'], d)} / {f(row['p95'], d)} / {f(row['p99'], d)}"


def campaign(c, mbb):
    o = load(RUN / c / "analysis/outcomes.json")
    st = {r["stage"]: r for r in load(RUN / c / "analysis/stage_percentiles.csv")}
    m = load(RUN / mbb / "mbb_summary.json")
    rej = o.get("reject_messages", {})
    return {"o": o, "st": st, "mbb": m,
            "msd_profile_rejections": sum(v for k, v in rej.items() if "exceeds physical switch MSD" in k),
            "depth_mismatch_rejections": sum(v for k, v in rej.items() if "does not match materialized" in k)}


def main():
    GEN.mkdir(parents=True, exist_ok=True)
    cs = {k: campaign(c, m) for k, c, m in CAMPAIGNS}
    rp = RUN / "supplemental_probes/corrected_model_after_vxlan_fix/reprobe_summary.json"
    reprobe = load(rp) if rp.exists() else []
    rows = [("Offered requests", lambda c: n(c["o"]["offered"])),
            ("Admitted (HTTP 200)", lambda c: n(c["o"]["admitted_http200"])),
            ("Steering confirmed by controller", lambda c: n(c["o"]["steered"])),
            ("Installed rules read back on every path switch", lambda c: n(c["o"]["readback_all_present"])),
            ("Rejected: MSD depth $\\neq$ materialized path depth", lambda c: n(c["depth_mismatch_rejections"])),
            ("Rejected: path exceeds switch MSD profile", lambda c: n(c["msd_profile_rejections"])),
            ("Probes with 20/20 packets at the VNF", lambda c: f"{n(c['o']['probes_with_full_delivery'])} / {n(c['o']['steered'])}"),
            ("Probe packets received / sent", lambda c: f"{n(c['o']['probe_packets_received'])} / {n(c['o']['probe_packets_sent'])}"),
            ("Migrations; make-before-break order held", lambda c: f"{n(c['mbb']['migrations'])}; {n(c['mbb']['order_ok'])}"),
            ("Migrations completed (old VNF absence confirmed)", lambda c: n(c["mbb"]["final_states"].get("COMPLETED", 0))),
            ("Admission API response (s)", lambda c: pcts(c["st"]["admit_s"], 3)),
            ("Tekton PipelineRun duration (s)", lambda c: pcts(c["st"]["pipelinerun_duration_s"], 0)),
            ("Deployment start to Pod Ready (s)", lambda c: pcts(c["st"]["make_to_pod_ready_k8s_s"], 1)),
            ("Rule installation and readback confirmation (s)", lambda c: pcts(c["st"]["rule_install_and_confirm_s"], 2)),
            ("Submission to steering confirmation (s)", lambda c: pcts(c["st"]["submit_to_steer_confirm_s"], 1)),
            ("Probe RTT through SRv6, per-probe median (ms)", lambda c: pcts(c["st"]["probe_rtt_p50_ms"], 1))]
    t = ["% Generated by scripts/paper/make_hil_e2e.py; do not hand-edit.",
         "\\begin{tabular}{@{}lrr@{}}", "\\toprule",
         "Metric (P50 / P95 / P99 where timed) & Corrected checkpoint & Pre-correction checkpoint \\\\", "\\midrule"]
    t += [f"{lab} & {fn(cs['corrected'])} & {fn(cs['legacy'])} \\\\" for lab, fn in rows]
    t += ["\\bottomrule", "\\end{tabular}"]
    (GEN / "table_hil_e2e_detailed.tex").write_text("\n".join(t) + "\n")
    compact = ["% Generated by scripts/paper/make_hil_e2e.py; do not hand-edit.",
               "\\begin{tabularx}{\\columnwidth}{@{}>{\\raggedright\\arraybackslash}Xr@{}}",
               "\\toprule", "Metric & Corrected checkpoint \\\\", "\\midrule"]
    compact += [f"{lab} & {fn(cs['corrected'])} \\\\" for lab, fn in rows]
    compact += ["\\bottomrule", "\\end{tabularx}"]
    (GEN / "table_hil_e2e.tex").write_text("\n".join(compact) + "\n")

    iso = load(OVERMSD)["rows"]
    live = load(RUN / "live_fault_injection/summary.json")
    m = ["% Generated by scripts/paper/make_hil_e2e.py; do not hand-edit.",
         "\\begin{tabular}{@{}llrlrrl@{}}", "\\toprule",
         "Experiment & Path (per-switch MSD) & Depth & Admission & Rules & Rx / Tx & Counter \\\\",
         "\\midrule"]
    mc = ["% Generated by scripts/paper/make_hil_e2e.py; do not hand-edit.",
          "\\begin{tabular}{@{}lrlll@{}}", "\\toprule",
          "Case & Depth & Decision/rules & Rx/Tx & Drop \\\\", "\\midrule"]
    for r in iso:
        if r["case"] == "in_limit_depth2":
            continue
        drops = ", ".join(f"{k} +{v}" for k, v in json.loads(r["msd_drops_by_switch"] or "{}").items()) or "0"
        lim = dict(x.split("=") for x in r["switch_msd"].split())
        path = "-".join(r["switch_path"].split("-")) + " (" + ",".join(lim[x] for x in r["switch_path"].split("-")) + ")"
        m.append(f"Isolated, {r['mode']} & {path} & {r['sid_depth']} & {r['admission_decision']} & "
                 f"{r['rules_installed_per_trial']} & {n(r['packets_received'])} / {n(r['packets_sent'])} & {drops} \\\\")
        mc.append(f"I/{'P' if r['mode'] == 'protected' else 'B'} & {r['sid_depth']} & "
                  f"{r['admission_decision']}/{r['rules_installed_per_trial']} & "
                  f"{n(r['packets_received'])}/{n(r['packets_sent'])} & {drops} \\\\")
    m.append("\\midrule")
    mc.append("\\midrule")
    for cse in live["cases"]:
        at = [s for s, v in live["counter_delta"].items() if v["msd_violation"] == cse["sent"]]
        # attribute each depth's drop to the first switch whose MSD is below the SRH depth
        msd = {a: int(b) for a, b in re.findall(r"(s\d+)\((\d+)\)", live["path"])}
        hit = next((x for x in msd if cse["srh_depth"] > msd[x]), None)
        drop = f"{hit} +{cse['sent']}" if hit and hit in at else "0"
        sw = re.findall(r"(s\d+)\((\d+)\)", live["path"])
        m.append(f"Live, admitted path & {'-'.join(a for a, _ in sw)} ({','.join(b for _, b in sw)}) & {cse['srh_depth']} & "
                 f"{'at admitted depth' if cse['srh_depth'] == live['admitted_depth'] else 'bypassed'} & installed & "
                 f"{n(cse['echo_replies'])} / {n(cse['sent'])} & {drop} \\\\")
        mc.append(f"L & {cse['srh_depth']} & "
                  f"{'admit' if cse['srh_depth'] == live['admitted_depth'] else 'bypass'}/yes & "
                  f"{n(cse['echo_replies'])}/{n(cse['sent'])} & {drop} \\\\")
    m += ["\\bottomrule", "\\end{tabular}"]
    (GEN / "table_hil_msd_detailed.tex").write_text("\n".join(m) + "\n")
    mc += ["\\bottomrule", "\\end{tabular}"]
    (GEN / "table_hil_msd.tex").write_text("\n".join(mc) + "\n")

    lrs = {}
    for k, d in LONGRUNS:
        p = RUN / d / "analysis/longrun_summary.json"
        if p.exists():
            lrs[k] = load(p)
    lab = {"released": "After capacity release"}
    cols = list(lrs)
    L = ["% Generated by scripts/paper/make_hil_e2e.py; do not hand-edit.",
         "\\begin{tabularx}{\\columnwidth}{@{}>{\\raggedright\\arraybackslash}Xr@{}}", "\\toprule",
         "Metric & " + " & ".join(lab[c] for c in cols) + " \\\\", "\\midrule"]

    def row(name, fn):
        L.append(name + " & " + " & ".join(fn(lrs[c]) for c in cols) + " \\\\")
    row("Duration (h); request interval (s)", lambda s: "3; 3.5")
    row("Active VNFs at end; mean ledger CPU utilization (\\%)", lambda s: f"{s['state_after']['active_vnfs']}; "
        f"{sum(s['state_after']['node_cpu_util'].values()) / len(s['state_after']['node_cpu_util']):.1f}")
    row("Admission requests; admitted", lambda s: f"{n(s['admission']['requests'])}; {n(s['admission']['accepted'])}")
    row("Rejected: MSD; no safe action", lambda s: f"{n(s['admission']['reject_reason'].get('msd_violation', 0))}; "
        f"{n(s['admission']['reject_reason'].get('no_safe_action', 0))}")
    row("Admitted MSD violations; timeouts", lambda s: f"{s['admission']['admitted_violations']}; {s['admission']['timeouts']}")
    row("Backend decision latency P50/P95/P99 (ms)", lambda s: pcts(s["admission"]["decision_latency_ms"], 1))
    row("Readiness samples with all Deployments Ready", lambda s: f"{n(s['kubernetes']['samples_all_ready'])} / {n(s['kubernetes']['samples'])} "
        f"({'/'.join(s['kubernetes']['deployments'])} Deployments)")
    row("Data-plane rounds; VNFs probed", lambda s: f"{n(s['dataplane']['rounds'])}; {n(s['dataplane']['distinct_vnfs_probed'])}")
    row("Packets received / sent", lambda s: f"{n(s['dataplane']['received'])} / {n(s['dataplane']['sent'])}")
    row("Pod IP changes; \\texttt{msd\\_violation} increments", lambda s: f"{s['dataplane']['pod_ip_changed']}; {s['dataplane']['msd_violation_delta_total']}")
    L += ["\\bottomrule", "\\end{tabularx}"]
    (GEN / "table_hil_longrun.tex").write_text("\n".join(L) + "\n")

    c = cs["corrected"]
    macros = {"HILEtoEOffered": n(c["o"]["offered"]), "HILEtoESteered": n(c["o"]["steered"]),
              "HILEtoEFullProbes": n(c["o"]["probes_with_full_delivery"]),
              "HILEtoESubmitSteerPNF": f(c["st"]["submit_to_steer_confirm_s"]["p95"], 1),
              "HILEtoESubmitSteerPF": f(c["st"]["submit_to_steer_confirm_s"]["p50"], 1),
              "HILEtoEMigrations": n(c["mbb"]["migrations"]),
              "HILEtoEReprobeOK": n(sum(1 for r in reprobe if isinstance(r.get("result"), dict)
                                        and r["result"]["received"] == r["result"]["sent"])),
              "HILEtoEReprobeN": n(sum(1 for r in reprobe if isinstance(r.get("result"), dict)))}
    if "released" in lrs:
        s = lrs["released"]
        macros.update({"HILLongPackets": n(s["dataplane"]["sent"]), "HILLongRecv": n(s["dataplane"]["received"]),
                       "HILLongRequests": n(s["admission"]["requests"])})
    (GEN / "hil_e2e_numbers.tex").write_text("% Generated by scripts/paper/make_hil_e2e.py.\n" + "".join(
        f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()))
    (GEN / "hil_e2e.json").write_text(json.dumps({"sources_sha256": used, "macros": macros,
                                                  "reprobe": reprobe, "longruns": list(lrs)}, indent=1))
    print(json.dumps(macros, indent=1))


if __name__ == "__main__":
    main()
