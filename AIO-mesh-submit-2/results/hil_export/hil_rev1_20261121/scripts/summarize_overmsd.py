#!/usr/bin/env python3
"""Aggregate the isolated protected/bypass over-MSD trials into the P1-3 table.

Input : 04_new_experiments/overmsd_isolated_20261121/raw/results.json (+ plan.json)
Output: generated/overmsd/overmsd_table.csv, overmsd_table.tex, overmsd_summary.json
Totals are sums over trials; denominators are packets sent. No value is imputed.
Usage: python3 scripts/summarize_overmsd.py <export_root>
"""
from __future__ import annotations

import csv
import json
import sys
from collections import OrderedDict
from pathlib import Path


def pct(values, q):
    s = sorted(values)
    return s[max(0, min(len(s) - 1, round((q / 100.0) * (len(s) - 1))))] if s else None


def main() -> int:
    export = Path(sys.argv[1]).resolve()
    base = export / "04_new_experiments/overmsd_isolated_20261121"
    res = json.loads((base / "raw/results.json").read_text())["results"]
    plan = json.loads((base / "plan.json").read_text())
    groups: "OrderedDict[tuple, list]" = OrderedDict()
    for r in res:
        groups.setdefault((r["case"], r["mode"]), []).append(r)
    rows = []
    for (case, mode), rs in groups.items():
        sent = sum(r["packets_sent"] for r in rs)
        recv = sum(r["packets_received_sink"] for r in rs)
        drops_by_switch: dict = {}
        for r in rs:
            for sw, d in r["counter_delta"].items():
                if d["msd_violation_counter"]:
                    drops_by_switch[sw] = drops_by_switch.get(sw, 0) + d["msd_violation_counter"]
        r0 = rs[0]
        rows.append({
            "case": case, "mode": mode, "trials": len(rs),
            "switch_path": "-".join(r0["switch_path"]),
            "switch_msd": " ".join("{}={:g}".format(k, v) for k, v in r0["switch_msd"].items()),
            "sid_depth": r0["sid_depth"],
            "sid_list_final_to_first": " ".join(r0["sid_stack_final_to_first"]),
            "admission_decision": r0["admission_decision"],
            "admission_error": r0["admission_error"] or "",
            "rules_installed_per_trial": r0["rules_installed"],
            "rules_readback_present_all_trials": all(r["rules_readback_present"] == r["rules_installed"] for r in rs),
            "rejected_rules_absent_all_trials": all(r["rejected_rules_absent"] for r in rs),
            "unexpected_table_entries": sum(r["unexpected_entries"] for r in rs),
            "packets_sent": sent, "packets_received": recv, "loss": sent - recv,
            "loss_percent": "{:.2f}".format(100.0 * (sent - recv) / sent) if sent else "n/a (no packets steered)",
            "msd_drops_total": sum(r["msd_drops_total_delta"] for r in rs),
            "msd_drops_by_switch": json.dumps(drops_by_switch),
            "install_ms_p50": pct([r["install_ms"] for r in rs], 50),
            "readback_ms_p50": pct([r["readback_ms"] for r in rs], 50),
        })
    out = export / "generated/overmsd"
    out.mkdir(parents=True, exist_ok=True)
    with (out / "overmsd_table.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    lines = [
        "% Generated by scripts/summarize_overmsd.py from 04_new_experiments/overmsd_isolated_20261121/raw/results.json",
        "\\begin{tabular}{@{}llrlrrrrl@{}}", "\\toprule",
        "Case & Mode & Depth & Admission & Rules & Sent & Recv. & MSD drops & Drop switch \\\\", "\\midrule"]
    for r in rows:
        lines.append("{} & {} & {} & {} & {} & {} & {} & {} & {} \\\\".format(
            r["case"].replace("_", "\\_"), r["mode"], r["sid_depth"], r["admission_decision"],
            r["rules_installed_per_trial"], r["packets_sent"], r["packets_received"], r["msd_drops_total"],
            ", ".join(json.loads(r["msd_drops_by_switch"]).keys()) or "--"))
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "overmsd_table.tex").write_text("\n".join(lines) + "\n")
    summary = {"protocol": plan["protocol"], "trials_per_case_mode": plan["trials"],
               "packets_per_trial": plan["packets_per_trial"], "rows": rows,
               "scope": "Isolated BMv2 (software switch) in a network-less container; profiles hash-identical to "
                        "the live s1-s10 JSON. Not ASIC evidence; not the live Mininet topology; protected mode "
                        "means the admission function rejected the request so no rule or packet was steered."}
    (out / "overmsd_summary.json").write_text(json.dumps(summary, indent=2))
    for r in rows:
        print(r["case"], r["mode"], r["admission_decision"], "rules", r["rules_installed_per_trial"],
              "sent", r["packets_sent"], "recv", r["packets_received"], "msd_drops", r["msd_drops_total"], r["msd_drops_by_switch"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
