#!/usr/bin/env python3
"""Summarize the live admission concurrency sweep (attempt 2) by concurrency level.

Input : 04_new_experiments/admission_concurrency_attempt2/{per_request.csv,per_seed_level_summary.csv,free_calls.csv}
Output: generated/concurrency/concurrency_by_level.csv and .tex
Throughput = completed HTTP operations / measured wall time per (seed, level);
it is never derived from a latency percentile. Percentiles use the same
rounded-rank rule as the testbed metrics module and are pooled over seeds.
Server-side timings exist only for admitted (HTTP 200) responses.
Usage: python3 scripts/summarize_concurrency.py <export_root>
"""
from __future__ import annotations

import csv
import json
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path


def pct(values, q):
    s = sorted(values)
    return round(s[max(0, min(len(s) - 1, round((q / 100.0) * (len(s) - 1))))], 3) if s else ""


def main() -> int:
    root = Path(sys.argv[1]).resolve()
    base = root / "04_new_experiments/admission_concurrency_attempt2"
    req = list(csv.DictReader((base / "per_request.csv").open()))
    lev = list(csv.DictReader((base / "per_seed_level_summary.csv").open()))
    frees = list(csv.DictReader((base / "free_calls.csv").open()))
    by = defaultdict(list)
    for r in req:
        by[int(r["concurrency"])].append(r)
    thr = defaultdict(list)
    for l in lev:
        thr[int(l["concurrency"])].append(float(l["completed_ops_per_s"]))
    rows = []
    for c in sorted(by):
        rs = by[c]
        adm = [r for r in rs if r["admitted"] == "True"]
        rej = [r for r in rs if r["admitted"] != "True"]
        reasons = Counter(r["reason_key"] or r["error_code"] or "http_" + r["http_status"] for r in rej)
        rows.append({
            "concurrency": c, "seeds": len(thr[c]), "offered": len(rs), "admitted": len(adm), "rejected": len(rej),
            "admit_rate_percent": round(100.0 * len(adm) / len(rs), 2),
            "rejection_reasons": json.dumps(dict(sorted(reasons.items()))),
            "http_5xx_or_timeout": sum(r["http_status"] not in ("200", "409") for r in rs),
            "throughput_ops_s_mean": round(statistics.mean(thr[c]), 3),
            "throughput_ops_s_min": round(min(thr[c]), 3), "throughput_ops_s_max": round(max(thr[c]), 3),
            "rtt_all_p50_ms": pct([float(r["client_rtt_ms"]) for r in rs], 50),
            "rtt_all_p95_ms": pct([float(r["client_rtt_ms"]) for r in rs], 95),
            "rtt_all_p99_ms": pct([float(r["client_rtt_ms"]) for r in rs], 99),
            "rtt_admitted_p50_ms": pct([float(r["client_rtt_ms"]) for r in adm], 50),
            "rtt_admitted_p95_ms": pct([float(r["client_rtt_ms"]) for r in adm], 95),
            "rtt_rejected_p50_ms": pct([float(r["client_rtt_ms"]) for r in rej], 50),
            "rtt_rejected_p95_ms": pct([float(r["client_rtt_ms"]) for r in rej], 95),
            "server_handler_admitted_p50_ms": pct([float(r["server_decision_ms"]) for r in adm if r["server_decision_ms"]], 50),
            "server_handler_admitted_p95_ms": pct([float(r["server_decision_ms"]) for r in adm if r["server_decision_ms"]], 95),
            "server_handler_admitted_p99_ms": pct([float(r["server_decision_ms"]) for r in adm if r["server_decision_ms"]], 99),
            "wait_outside_handler_admitted_p50_ms": pct([float(r["est_wait_outside_handler_ms"]) for r in adm if r["est_wait_outside_handler_ms"]], 50),
            "wait_outside_handler_admitted_p95_ms": pct([float(r["est_wait_outside_handler_ms"]) for r in adm if r["est_wait_outside_handler_ms"]], 95),
            "wait_outside_handler_admitted_p99_ms": pct([float(r["est_wait_outside_handler_ms"]) for r in adm if r["est_wait_outside_handler_ms"]], 99),
            "policy_inference_admitted_p95_ms": pct([float(r["policy_inference_ms"]) for r in adm if r["policy_inference_ms"]], 95),
            "admission_validation_admitted_p95_ms": pct([float(r["admission_validation_ms"]) for r in adm if r["admission_validation_ms"]], 95),
            "actuation_requested": sum(bool(r["actuation"]) for r in rs),
            "releases_ok": sum(f["ok"] == "True" for f in frees if f["request_id"].split("-c")[1][:2] == "%02d" % c),
        })
    out = root / "generated/concurrency"
    out.mkdir(parents=True, exist_ok=True)
    with (out / "concurrency_by_level.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    lines = ["% Generated by scripts/summarize_concurrency.py (live API, admission only, no actuation)",
             "\\begin{tabular}{@{}rrrrrrrrr@{}}", "\\toprule",
             "$C$ & Offered & Admitted & Ops/s & RTT P50 & RTT P95 & RTT P99 & Handler P95$^a$ & Wait P95$^a$ \\\\", "\\midrule"]
    for r in rows:
        lines.append("{} & {} & {} & {:.2f} & {} & {} & {} & {} & {} \\\\".format(
            r["concurrency"], r["offered"], r["admitted"], r["throughput_ops_s_mean"], r["rtt_all_p50_ms"],
            r["rtt_all_p95_ms"], r["rtt_all_p99_ms"], r["server_handler_admitted_p95_ms"],
            r["wait_outside_handler_admitted_p95_ms"]))
    lines += ["\\bottomrule", "\\end{tabular}", "% a: admitted requests only (server timings are returned only with HTTP 200)."]
    (out / "concurrency_by_level.tex").write_text("\n".join(lines) + "\n")
    for r in rows:
        print({k: r[k] for k in ("concurrency", "offered", "admitted", "throughput_ops_s_mean", "rtt_all_p95_ms",
                                 "server_handler_admitted_p95_ms", "wait_outside_handler_admitted_p95_ms",
                                 "rejection_reasons", "http_5xx_or_timeout", "releases_ok")})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
