#!/usr/bin/env python3
"""Aggregate the SID-depth-7 injection trials (todo-2 E6) into one table.

Input : 04_new_experiments/sid7_injection_isolated_20261121/raw/results.json
Output: generated/injection7/injection7_table.csv and .tex
Usage: python3 scripts/summarize_injection7.py <export_root>
"""
from __future__ import annotations

import csv
import json
import sys
from collections import OrderedDict
from pathlib import Path


def main() -> int:
    root = Path(sys.argv[1]).resolve()
    res = json.loads((root / "04_new_experiments/sid7_injection_isolated_20261121/raw/results.json").read_text())["results"]
    groups: "OrderedDict[tuple, list]" = OrderedDict()
    for r in res:
        groups.setdefault((r["case"], r["mode"]), []).append(r)
    rows = []
    for (case, mode), rs in groups.items():
        drops: dict = {}
        advance: dict = {}
        for r in rs:
            for sw, d in r["counter_delta"].items():
                drops[sw] = drops.get(sw, 0) + d["msd_violation_counter"]
                advance[sw] = advance.get(sw, 0) + d["srv6_advance_counter"]
        sent = sum(r["packets_sent"] for r in rs)
        recv = sum(r["packets_received_sink"] for r in rs)
        rows.append({
            "case": case, "mode": mode, "trials": len(rs), "switch_path": "-".join(rs[0]["switch_path"]),
            "switch_msd": " ".join("{}={:g}".format(k, v) for k, v in rs[0]["switch_msd"].items()),
            "admitted_path_depth": rs[0].get("admitted_path_depth", rs[0]["sid_depth"]),
            "packet_sid_depth": rs[0]["sid_depth"], "admission_decision": rs[0]["admission_decision"],
            "rules_installed_per_trial": rs[0]["rules_installed"],
            "rules_readback_present_all_trials": all(r["rules_readback_present"] == r["rules_installed"] for r in rs),
            "packets_sent": sent, "packets_received": recv, "loss": sent - recv,
            "msd_drops_by_switch": json.dumps({k: v for k, v in drops.items() if v}),
            "advance_by_switch": json.dumps({k: v for k, v in advance.items() if v}),
        })
    out = root / "generated/injection7"
    out.mkdir(parents=True, exist_ok=True)
    with (out / "injection7_table.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    lines = ["% Generated by scripts/summarize_injection7.py", "\\begin{tabular}{@{}llrrrrrl@{}}", "\\toprule",
             "Path & Packet & Adm. depth & SID depth & Sent & Recv. & MSD drops & Drop switch \\\\", "\\midrule"]
    for r in rows:
        d = json.loads(r["msd_drops_by_switch"])
        lines.append("{} & {} & {} & {} & {} & {} & {} & {} \\\\".format(
            r["switch_path"], r["mode"].replace("_", "\\_"), r["admitted_path_depth"], r["packet_sid_depth"],
            r["packets_sent"], r["packets_received"], sum(d.values()), ", ".join(d) or "--"))
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "injection7_table.tex").write_text("\n".join(lines) + "\n")
    for r in rows:
        print(r["case"], r["packets_sent"], r["packets_received"], r["msd_drops_by_switch"], r["advance_by_switch"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
