"""Export reusable manuscript values for the measured HIL run and load contrasts."""
import csv
import json
from pathlib import Path

_BASE = Path(__file__).resolve().parents[2]
ROOT = _BASE / "docs/AIO-mesh-rev1"
OUT = ROOT / "generated"


def main():
    hil = json.loads((OUT / "table11.json").read_text())
    bundle = _BASE if _BASE.name == "AIO-mesh-submit-2" else _BASE / "AIO-mesh-submit-2"
    source = bundle / "docs/AIO-mesh-rev1/evidence/load_sweep/mentor_b2_load_sweep_21.csv"
    if not source.is_file():
        source = ROOT / "evidence/load_sweep/mentor_b2_load_sweep_21.csv"
    with source.open() as stream:
        sweep = list(csv.DictReader(stream))
    values = {"HILRequests": f"{hil['requests']:,}"}
    for multiplier, name in [("1.2", "SweepPeakGain"), ("1.5", "SweepFinalGain")]:
        gains = [float(row["mean_delta_pp"]) for row in sweep
                 if row["load_multiplier"] == multiplier]
        if len(gains) != 3:
            raise ValueError(f"Expected three topology differences at multiplier {multiplier}")
        values[name] = f"{min(gains):.2f}--{max(gains):.2f}"
    (OUT / "numbers.json").write_text(json.dumps(values, indent=2) + "\n")
    (OUT / "numbers.tex").write_text(
        "% Generated by scripts/paper/make_numbers.py.\n"
        + "\n".join(fr"\newcommand{{\{name}}}{{{value}}}" for name, value in values.items()) + "\n"
    )


if __name__ == "__main__":
    main()
